-- 与 db/migration/V2__accounts.sql 保持一致；H2 使用 IDENTITY 语法。
CREATE TABLE accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(64) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP(6) NOT NULL,
  created_by VARCHAR(64) NOT NULL,
  password_changed_at TIMESTAMP(6) NOT NULL,
  system_account BOOLEAN NOT NULL DEFAULT FALSE
);

-- 与 db/migration/V3__permissions.sql 保持一致。
CREATE TABLE permissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(100) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  description VARCHAR(500) NULL,
  created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE account_permissions (
  account_id BIGINT NOT NULL,
  permission_id BIGINT NOT NULL,
  granted_at TIMESTAMP(6) NOT NULL,
  granted_by VARCHAR(64) NOT NULL,
  PRIMARY KEY (account_id, permission_id),
  CONSTRAINT fk_ap_account FOREIGN KEY (account_id) REFERENCES accounts (id) ON DELETE CASCADE,
  CONSTRAINT fk_ap_permission FOREIGN KEY (permission_id) REFERENCES permissions (id) ON DELETE CASCADE
);

CREATE TABLE transfers (
  transfer_key VARCHAR(6) PRIMARY KEY,
  owner_id VARCHAR(100) NOT NULL,
  file_name VARCHAR(1000) NOT NULL,
  stored_name VARCHAR(255) NOT NULL,
  size_bytes BIGINT NOT NULL,
  expires_at TIMESTAMP(6) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL
);
